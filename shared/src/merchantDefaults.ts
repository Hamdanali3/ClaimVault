export function findBuiltinMerchantRule(
  normalizedMerchant: string,
  rawText?: string,
): MerchantRuleEntry | null {
  const haystack = `${normalizedMerchant} ${(rawText ?? '').toLowerCase()}`;
  // Exact key match first
  for (const rule of BUILTIN_MERCHANT_RULES) {
    if (normalizedMerchant === rule.normalizedKey) return rule;
  }
  // Alias match
  for (const rule of BUILTIN_MERCHANT_RULES) {
    for (const alias of rule.aliases) {
      if (
        normalizedMerchant.includes(alias) ||
        alias.includes(normalizedMerchant && normalizedMerchant.length > 2 ? normalizedMerchant : '___')
      ) {
        return rule;
      }
    }
  }
  // Fallback scan in raw text if merchant name was vague
  if (rawText) {
    for (const rule of BUILTIN_MERCHANT_RULES) {
      for (const alias of rule.aliases) {
        if (alias.length >= 4 && haystack.includes(alias)) {
          return rule;
        }
      }
    }
  }
  return null;
}
